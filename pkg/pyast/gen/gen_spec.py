#!/usr/bin/env python3
"""Generates spec_gen.go from the running interpreter's _ast module.

Run with CPython 3.15:  python3 gen/gen_spec.py > spec_gen.go
"""
import _ast, re, sys

def norm(t):
    s = str(t)
    lst = opt = False
    m = re.fullmatch(r"list\[(.*)\]", s)
    if m:
        lst, s = True, m.group(1)
    if s.endswith(" | None"):
        opt, s = True, s[:-7]
    m = re.fullmatch(r"<class '(?:ast\.)?(\w+)'>", s)
    if m:
        s = m.group(1)
    s = s.replace("ast.", "")
    return s, lst, opt

classes = []
for name, c in vars(_ast).items():
    if isinstance(c, type) and issubclass(c, _ast.AST) and c is not _ast.AST and c.__module__ in ("ast", "_ast"):
        classes.append(c)
# stable order: bases before derived, then name
def depth(c):
    return len(c.__mro__)
classes.sort(key=lambda c: (depth(c), c.__name__))
print("// Code generated by gen/gen_spec.py from CPython %d.%d; DO NOT EDIT.\n" % sys.version_info[:2])
print("package pyast\n")
print("var specTable = []Spec{")
for c in classes:
    base = c.__bases__[0].__name__
    fields = getattr(c, "_fields", ())
    attrs = getattr(c, "_attributes", ())
    ft = getattr(c, "_field_types", {})
    print("\t{Name: %r, Base: %r," % (c.__name__, base if base != "AST" else ""), end="")
    # strings as Go strings
    def q(x): return '"' + x + '"'
    print(" Fields: []Field{" + ", ".join(
        "{%s, %s, %s, %s}" % (q(f), q(norm(ft[f])[0]), str(norm(ft[f])[1]).lower(), str(norm(ft[f])[2]).lower()) for f in fields) + "},", end="")
    print(" Attrs: []string{" + ", ".join(q(a) for a in attrs) + "}},")
print("}")
